    --keep) KEEP=1; shift ;;
    -V|--version) printf 'install.sh %s\n' "${APP_VERSION}"; exit 0 ;;
    -h|--help) usage; exit 0 ;;
    --) shift; while [ $# -gt 0 ]; do PASS_ARGS+=("$1"); shift; done ;;
    *) PASS_ARGS+=("$1"); shift ;;
  esac
done
