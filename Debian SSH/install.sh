# ---------- 工具函数 ----------
sha256_of() {
    if command -v sha256sum >/dev/null 2>&1; then
        sha256sum "$1" | awk '{print $1}'
    elif command -v shasum >/dev/null 2>&1; then
        shasum -a 256 "$1" | awk '{print $1}'
    else
        return 1
    fi
}

decode_payload() {
    local dest="$1"
    # 优先 GNU base64 -d，失败则回退 BSD base64 -D
    if printf '%s' "$PAYLOAD_B64" | base64 -d 2>/dev/null | tar -xzf - -C "$dest" 2>/dev/null; then
        return 0
    fi
    printf '%s' "$PAYLOAD_B64" | base64 -D 2>/dev/null | tar -xzf - -C "$dest" 2>/dev/null
}

# 创建临时目录（仅面向 Linux：mktemp -d 返回标准 POSIX 路径）
make_tmpdir() {
    mktemp -d
}

verify_payload() {
    local dest="$1" line sum name actual fail=0
    while IFS= read -r line; do
        if [[ -z "$line" ]]; then
            continue
        fi
        sum="${line%%  *}"
        name="${line#*  }"
        if ! actual="$(sha256_of "$dest/$name")"; then
            warn "缺少 sha256sum/shasum，跳过完整性校验"
            return 0
        fi
        if [[ "$sum" != "$actual" ]]; then
            err "校验失败: $name"
            fail=1
        fi
    done <<< "$MANIFEST"
    return "$fail"
}

# ---------- 别名注入 ----------
ALIAS_BEGIN="# >>> ssh-port-tool >>>"
ALIAS_END="# <<< ssh-port-tool <<<"

# alias 块内容：使用 sshh 作为入口，不覆盖系统自带的 ssh 命令
alias_block() {
    cat <<EOF
${ALIAS_BEGIN}
# Debian SSH 端口管理工具：输入 sshh 打开交互面板
# 刻意不占用 ssh，避免与系统命令冲突；ssh 仍为原生客户端，行为不变
# 如需直接运行面板而不依赖别名：ssh-port
alias sshh='ssh-port'
${ALIAS_END}
EOF
}

# 解析需要写入别名的用户 home 目录。
# 关键：sudo 下 $HOME 是 /root，而 $SUDO_USER 是"用户名"不是路径，
# 直接把它当目录用会导致普通用户的 rc 被静默跳过（装完 sshh 不生效）。
resolve_user_home() {
    local user="${SUDO_USER:-}" home=""
    if [[ -n "$user" && "$user" != "root" ]]; then
        if command -v getent >/dev/null 2>&1; then
            home="$(getent passwd "$user" 2>/dev/null | awk -F: '{print $6; exit}')" || home=""
        fi
        if [[ -z "$home" && -r /etc/passwd ]]; then
            home="$(awk -F: -v u="$user" '$1==u{print $6; exit}' /etc/passwd 2>/dev/null)" || home=""
        fi
    fi
    # 解析失败或目录不存在时退回当前 $HOME
    if [[ -z "$home" || ! -d "$home" ]]; then
        home="${HOME:-/root}"
    fi
    printf '%s' "$home"
}

# 向指定 rc 文件注入 alias 块（幂等：已存在则先移除旧块）
inject_alias() {
    local rc="$1"
    [[ -n "$rc" ]] || return 0
    # 缺失的 rc 由 install_alias 统一补建，这里只处理确实存在的文件
    [[ -f "$rc" ]] || return 0

    # 记录原属主：sudo 下 sed -i 会重建文件，属主会变成 root，
    # 导致用户之后无法编辑自己的 .bashrc
    local owner group
    owner="$(stat -c '%u' "$rc" 2>/dev/null)" || owner=""
    group="$(stat -c '%g' "$rc" 2>/dev/null)" || group=""

    # 已存在旧块 → 先删除，保证幂等
    if grep -qF "$ALIAS_BEGIN" "$rc" 2>/dev/null; then
        sed -i "\|^${ALIAS_BEGIN}\$|,\|^${ALIAS_END}\$|d" "$rc" 2>/dev/null || true
    fi
    printf '\n%s\n' "$(alias_block)" >> "$rc"

    if [[ -n "$owner" && -n "$group" && $EUID -eq 0 ]]; then
        chown "$owner:$group" "$rc" 2>/dev/null || true
    fi
}

remove_alias() {
    local rc
    for rc in "$@"; do
        [[ -f "$rc" ]] || continue
        if grep -qF "$ALIAS_BEGIN" "$rc" 2>/dev/null; then
            local owner group
            owner="$(stat -c '%u' "$rc" 2>/dev/null)" || owner=""
            group="$(stat -c '%g' "$rc" 2>/dev/null)" || group=""
            sed -i "\|^${ALIAS_BEGIN}\$|,\|^${ALIAS_END}\$|d" "$rc" 2>/dev/null || true
            if [[ -n "$owner" && -n "$group" && $EUID -eq 0 ]]; then
                chown "$owner:$group" "$rc" 2>/dev/null || true
            fi
            ok "已清理别名配置：$rc"
        fi
    done
}

install_alias() {
    local target_home
    target_home="$(resolve_user_home)"

    # 当前登录用户 + root，各家 shell 配置都处理
    local homes=() rc home owner has_rc injected=0
    homes+=("$target_home")
    if [[ "$target_home" != "/root" && -d /root ]]; then
        homes+=("/root")
    fi

    for home in "${homes[@]}"; do
        [[ -d "$home" ]] || continue

        # 一个 rc 都没有时创建 .bashrc：否则 inject_alias 会静默跳过，
        # 安装器却提示"已注入"，用户装完输入 sshh 提示命令不存在。
        has_rc=0
        for rc in "$home/.bashrc" "$home/.zshrc"; do
            if [[ -f "$rc" ]]; then has_rc=1; fi
        done
        if [[ $has_rc -eq 0 ]]; then
            rc="$home/.bashrc"
            printf '%s\n' "# 由 ssh-port-tool 创建" > "$rc" || continue
            owner="$(stat -c '%u:%g' "$home" 2>/dev/null)" || owner=""
            if [[ -n "$owner" && $EUID -eq 0 ]]; then
                chown "$owner" "$rc" 2>/dev/null || true
            fi
            warn "未找到 shell 配置文件，已创建：$rc"
        fi

        for rc in "$home/.bashrc" "$home/.zshrc"; do
            if [[ -f "$rc" ]]; then
                inject_alias "$rc"
                injected=$((injected + 1))
            fi
        done
    done

    if [[ $injected -eq 0 ]]; then
        warn "未能写入任何 shell 配置，请手动添加：alias sshh='ssh-port'"
    else
        ok "已注入 sshh 别名到 ${injected} 个配置文件（重新打开终端或执行 source ~/.bashrc 生效）"
    fi
}

# ---------- 安装 / 卸载 ----------
# 全局保存临时目录，便于 exec 前主动清理（exec 会跳过 EXIT trap）
TMP_INSTALL=""

do_install() {
    [[ -n "$DIR" && "$DIR" != "/" ]] || die "安装目录非法: '$DIR'"
    mkdir -p "$DIR" || die "无法创建目录 $DIR"

    TMP_INSTALL="$(make_tmpdir)" || die "无法创建临时目录"
    trap 'rm -rf "${TMP_INSTALL:-}" 2>/dev/null || true' EXIT

    info "解压安装包 ..."
    decode_payload "$TMP_INSTALL" || die "解压失败（base64/tar 不可用？）"

    # 解压结果自检：核心脚本必须到位
    local core
    for core in change_ssh_port.sh remove_old_ssh_port.sh ssh_menu.sh ssh-port.sh; do
        [[ -f "$TMP_INSTALL/$core" ]] || die "解压结果不完整，缺少 $core"
    done

    info "校验文件完整性 ..."
    verify_payload "$TMP_INSTALL" || die "完整性校验失败，已中止"

    info "安装到 $DIR ..."
    cp -f "$TMP_INSTALL/change_ssh_port.sh"     "$DIR/" || die "复制 change_ssh_port.sh 失败"
    cp -f "$TMP_INSTALL/remove_old_ssh_port.sh" "$DIR/" || die "复制 remove_old_ssh_port.sh 失败"
    cp -f "$TMP_INSTALL/ssh_menu.sh"            "$DIR/" || die "复制 ssh_menu.sh 失败"
    cp -f "$TMP_INSTALL/ssh-port.sh"            "$DIR/" || die "复制 ssh-port.sh 失败"
    cp -f "$TMP_INSTALL/check.sh"               "$DIR/" || die "复制 check.sh 失败"
    cp -f "$TMP_INSTALL/.shellcheckrc"          "$DIR/" 2>/dev/null || true
    chmod 755 "$DIR/change_ssh_port.sh" "$DIR/remove_old_ssh_port.sh" \
             "$DIR/ssh_menu.sh" "$DIR/ssh-port.sh" "$DIR/check.sh"

    if [[ $NO_DOC -eq 0 ]]; then
        cp -f "$TMP_INSTALL/README.md"   "$DIR/" 2>/dev/null || true
        cp -f "$TMP_INSTALL/使用文档.md" "$DIR/" 2>/dev/null || true
        chmod 644 "$DIR"/*.md 2>/dev/null || true
    fi

    # 命令软链
    if [[ -d /usr/local/bin && -w /usr/local/bin ]]; then
        ln -sf "$DIR/change_ssh_port.sh"     /usr/local/bin/ssh-port-change
        ln -sf "$DIR/remove_old_ssh_port.sh" /usr/local/bin/ssh-port-remove
        ln -sf "$DIR/ssh-port.sh"            /usr/local/bin/ssh-port
        ln -sf "$DIR/ssh_menu.sh"            /usr/local/bin/ssh-port-menu
        ok "已创建命令：ssh-port / ssh-port-menu / ssh-port-change / ssh-port-remove"
    else
        warn "未创建 /usr/local/bin 软链（目录不可写）"
    fi

    # 别名注入
    if [[ $NO_ALIAS -eq 0 ]]; then
        install_alias
    else
        info "已跳过 sshh 别名注入（--no-alias）"
    fi

    ok "安装完成：$DIR"
    printf '\n'
    printf '%s\n' "${BOLD}接下来怎么用：${NC}"
    printf '%s\n' "  ${GREEN}sshh${NC}                  打开交互式管理面板（推荐）"
    printf '%s\n' "  ${GREEN}ssh-port-menu${NC}         同上，直接命令"
    printf '%s\n' "  ${GREEN}sudo ssh-port-change${NC}  直接更换端口"
    printf '\n'
    printf '%s\n' "${DIM}提示：重新打开一个终端，或执行 source ~/.bashrc 让 sshh 生效。${NC}"
    printf '%s\n' "${DIM}      系统自带的 ssh 命令不受影响：ssh user@host 仍是原生客户端。${NC}"
    printf '%s\n' "${DIM}      若之前装过旧版（占用过 ssh），当前终端可执行 unalias ssh 清除残留。${NC}"
}

do_uninstall() {
    [[ -n "$DIR" && "$DIR" != "/" ]] || die "安装目录非法: '$DIR'"
    rm -f /usr/local/bin/ssh-port /usr/local/bin/ssh-port-menu \
          /usr/local/bin/ssh-port-change /usr/local/bin/ssh-port-remove

    local target_home
    target_home="$(resolve_user_home)"
    local homes=() rc
    homes+=("$target_home")
    if [[ "$target_home" != "/root" && -d /root ]]; then
        homes+=("/root")
    fi
    local home
    for home in "${homes[@]}"; do
        [[ -d "$home" ]] || continue
        for rc in "$home/.bashrc" "$home/.zshrc"; do
            remove_alias "$rc"
        done
    done

    if [[ -d "$DIR" ]]; then
        rm -rf "$DIR"
        ok "已删除 $DIR"
    else
        info "目录不存在：$DIR"
    fi
    ok "卸载完成。请重新打开终端（或执行 source ~/.bashrc）让 sshh 别名失效。"
}

# ---------- 主流程 ----------
main() {
    printf '%s\n' "${BOLD}==================================================${NC}"
    printf '%s\n' "${BOLD}   SSH 端口更换工具 · 安装器 v${VERSION}${NC}"
    printf '%s\n' "${BOLD}==================================================${NC}"
    printf '\n'
    [[ $EUID -eq 0 ]] || die "请使用 root 运行（sudo bash install.sh）"
    [[ "$(uname -s)" == "Linux" ]] || die "本工具仅支持 Linux（Debian/Ubuntu 等）"
    command -v tar    >/dev/null 2>&1 || die "缺少 tar"
    command -v base64 >/dev/null 2>&1 || die "缺少 base64"

    if [[ $DO_UNINSTALL -eq 1 ]]; then
        do_uninstall
        return 0
    fi

    if [[ $ASSUME_YES -ne 1 ]]; then
        local ans
        ans="$(prompt "将安装到 ${DIR}，继续？(Y/n) ")" || ans=""
        case "$ans" in
            [nN]) info "已取消"; exit 0 ;;
        esac
    fi

    do_install

    # exec 会替换进程，EXIT trap 不再触发，这里先主动清理临时目录
    if [[ $MENU_AFTER -eq 1 || $RUN_AFTER -eq 1 ]]; then
        rm -rf "${TMP_INSTALL:-}" 2>/dev/null || true
        TMP_INSTALL=""
        trap - EXIT
    fi

    if [[ $MENU_AFTER -eq 1 ]]; then
        printf '\n'
        info "启动交互式管理面板 ..."
        exec bash "$DIR/ssh_menu.sh" --menu
    fi

    if [[ $RUN_AFTER -eq 1 ]]; then
        printf '\n'
        info "启动更换端口脚本 ..."
        exec bash "$DIR/change_ssh_port.sh"
    fi
}

main "$@"
